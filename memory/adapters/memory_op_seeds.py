def seed_memory_ops(store, embedder, clock) -> int:
    """Insert the seed phrasings as memory_op_example prototypes when none exist yet."""
    if store.list(Status.CURRENT, [MemoryKind.MEMORY_OP_EXAMPLE]):
        return 0
    now = clock.now()
    count = 0
    for op, phrases in SEEDS.items():
        for text in phrases:
            store.add(Memory(
                id=str(uuid.uuid4()), kind=MemoryKind.MEMORY_OP_EXAMPLE, scope=GLOBAL_SCOPE,
                content=text, embedding=np.asarray(embedder.embed_text(text), dtype=np.float32),
                importance=0.5, status=Status.CURRENT, tier=Tier.ACTIVE, created_at=now,
                label=op.value,
            ))
            count += 1
    return count
